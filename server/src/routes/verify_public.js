router.get("/", async (req, res) => {
  try {
    const code = String(req.query.code || "").trim();
    const wantsJson =
      req.query.format === "json" ||
      (req.headers.accept || "").includes("application/json");

    if (!code) {
      if (wantsJson) {
        return res.status(400).json({ verified: false, error: "code_required" });
      }

      return res.status(400).send(
        renderPage({
          verified: false,
          details: "Verification code is required.",
        })
      );
    }

    const audit = await Audit.findOne({
      $or: [
        { verification_code: code },
        { "verification.payload.verify_code": code },
      ],
    })
      .sort({ created_at: -1 })
      .lean();

    if (!audit) {
      if (wantsJson) {
        return res.status(404).json({
          verified: false,
          error: "not_found",
          code,
        });
      }

      return res.status(404).send(
        renderPage({
          verified: false,
          code,
          details: "No matching stamp record was found for this verification code.",
        })
      );
    }

    const payload = audit?.verification?.payload || {};

    if (wantsJson) {
      return res.json({
        verified: true,
        source: "code",
        details: {
          stamp_id: audit.stamp_id || payload.stamp_id || null,
          document_id: audit.document_id || payload.doc_id || null,
          timestamp: audit.created_at || payload.ts || null,
          verification: audit.verification || null,
          meta: audit.meta || {},
        },
      });
    }

    return res.send(
      renderPage({
        verified: true,
        code,
        stampId: String(audit.stamp_id || payload.stamp_id || ""),
        documentId: String(audit.document_id || payload.doc_id || ""),
        timestamp: String(audit.created_at || payload.ts || ""),
        details: "Matching stamp audit record found.",
      })
    );
  } catch (e) {
    console.error("[verify_public GET] error", e);
    return res.status(500).send(
      renderPage({
        verified: false,
        code: req.query.code || "",
        details: "Verification failed due to a server error.",
      })
    );
  }
});

export default router;