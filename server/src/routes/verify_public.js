// GET by verification code
router.get("/", async (req, res) => {
  try {
    const code = req.query.code || "";
    const wantsJson =
      req.query.format === "json" ||
      (req.headers.accept || "").includes("application/json");

    if (!code) {
      if (wantsJson) {
        return res.status(400).json({ error: "code_required" });
      }

      return res
        .status(400)
        .send(
          renderPage({
            verified: false,
            code: "",
            details: "Verification code is required.",
          })
        );
    }

    const audit = await Audit.findOne({
      "verification.payload.verify_code": code,
    })
      .sort({ createdAt: -1 })
      .lean();

    if (!audit) {
      if (wantsJson) {
        return res.status(404).json({
          verified: false,
          error: "not_found",
          code,
        });
      }

      return res
        .status(404)
        .send(
          renderPage({
            verified: false,
            code,
            details: "No matching stamp record was found for this verification code.",
          })
        );
    }

    const payload = audit?.verification?.payload || {};

    if (wantsJson) {
      return res.json({
        verified: true,
        source: "code",
        details: {
          stamp_id: audit.stamp_id,
          document_id: audit.document_id,
          timestamp: audit.createdAt || payload.ts || null,
          verification: audit.verification || null,
        },
      });
    }

    return res.send(
      renderPage({
        verified: true,
        code,
        stampId: String(audit.stamp_id || payload.stamp_id || ""),
        documentId: String(audit.document_id || payload.doc_id || ""),
        timestamp: String(audit.createdAt || payload.ts || ""),
        details: "Matching stamp audit record found.",
      })
    );
  } catch (e) {
    console.error("[verify_public GET] error", e);
    return res.status(500).send(
      renderPage({
        verified: false,
        code: req.query.code || "",
        details: "Verification failed due to a server error.",
      })
    );
  }
});

// POST by uploaded PDF (kept for API/manual testing)
router.post("/", upload.single("file"), async (req, res) => {
  try {
    if (!req.file) {
      return res.status(400).json({ error: "file_required" });
    }

    const pdfBytes = fs.readFileSync(req.file.path);

    try {
      await PDFDocument.load(pdfBytes);
    } catch {
      return res.status(400).json({ error: "invalid_pdf" });
    }

    const audit = await Audit.findOne({})
      .sort({ createdAt: -1 })
      .lean();

    if (!audit) {
      return res.status(404).json({
        verified: false,
        error: "no_stamp_found",
      });
    }

    return res.json({
      verified: true,
      source: "pdf",
      stamp_id: audit.stamp_id,
      document_id: audit.document_id,
      timestamp: audit.createdAt,
    });
  } catch (e) {
    console.error("[verify_public POST] error", e);
    return res.status(500).json({ error: "verify_failed" });
  } finally {
    if (req.file?.path) {
      try {
        fs.unlinkSync(req.file.path);
      } catch {}
    }
  }
});

export default router;
