function getAdminRecipients(org) {
  const reports = org?.report_settings || {};
  const configured = Array.isArray(reports.analytics_recipients)
    ? reports.analytics_recipients.filter(Boolean).map((v) => String(v).trim())
    : [];

  if (configured.length) return configured;

  if (org?.owner_email) return [String(org.owner_email).trim()];

  return [];
}

function normalizeSettingsPayload(body = {}) {
  return {
    analytics_reports_enabled: !!body.analytics_reports_enabled,
    analytics_report_frequency:
      String(body.analytics_report_frequency || body.frequency || "weekly").toLowerCase() === "weekly"
        ? "weekly"
        : "weekly",
    analytics_report_day: String(body.analytics_report_day || body.sendDay || "monday").toLowerCase(),
    analytics_recipients: Array.isArray(body.analytics_recipients)
      ? body.analytics_recipients.filter(Boolean).map((v) => String(v).trim())
      : typeof body.analytics_recipients === "string"
      ? body.analytics_recipients.split(",").map((v) => v.trim()).filter(Boolean)
      : Array.isArray(body.recipients)
      ? body.recipients.filter(Boolean).map((v) => String(v).trim())
      : typeof body.recipients === "string"
      ? body.recipients.split(",").map((v) => v.trim()).filter(Boolean)
      : [],
  };
}

/* ---------------- GET SETTINGS ---------------- */

router.get("/orgs/reports/settings", requireAuth, async (req, res) => {
  try {
    const org = await getOrgForRequest(req);

    if (!org) {
      return res.json({
        analytics_reports_enabled: false,
        analytics_report_frequency: "weekly",
        analytics_report_day: "monday",
        analytics_recipients: [],
        last_analytics_report_sent_at: null,
      });
    }

    const reports = org.report_settings || {};

    return res.json({
      analytics_reports_enabled: !!reports.analytics_reports_enabled,
      analytics_report_frequency: reports.analytics_report_frequency || "weekly",
      analytics_report_day: reports.analytics_report_day || "monday",
      analytics_recipients: reports.analytics_recipients || [],
      last_analytics_report_sent_at: reports.last_analytics_report_sent_at || null,
    });
  } catch (err) {
    console.error("report settings read error:", err);
    return res.status(500).json({ error: "Failed to load settings" });
  }
});

/* ---------------- SAVE SETTINGS ---------------- */

router.post("/orgs/reports/settings", requireAuth, async (req, res) => {
  try {
    const featureCheck = await requireFeatureAccess(req, "analytics");
    if (!featureCheck.ok) return sendGateFailure(res, featureCheck);

    const org = featureCheck.org;
    if (!org) {
      return res.status(404).json({ error: "Organization not found" });
    }

    const normalized = normalizeSettingsPayload(req.body || {});

    org.report_settings = {
      ...(org.report_settings || {}),
      analytics_recipients: normalized.analytics_recipients,
      analytics_reports_enabled: normalized.analytics_reports_enabled,
      analytics_report_frequency: normalized.analytics_report_frequency,
      analytics_report_day: normalized.analytics_report_day,
      last_analytics_report_sent_at:
        org.report_settings?.last_analytics_report_sent_at || null,
    };

    await org.save();

    return res.json({
      success: true,
      report_settings: org.report_settings,
    });
  } catch (err) {
    console.error("report settings save error:", err);
    return res.status(500).json({ error: err?.message || "Save failed" });
  }
});

