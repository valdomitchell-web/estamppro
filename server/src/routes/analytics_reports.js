router.post("/orgs/reports/send-now", requireAuth, async (req, res) => {
  let run = null;

  try {
    const featureCheck = await requireFeatureAccess(req, "analytics");
    if (!featureCheck.ok) return sendGateFailure(res, featureCheck);

    const org = featureCheck.org;
    if (!org) {
      return res.status(404).json({ error: "Organization not found" });
    }

    const recipients = getAdminRecipients(org);
    if (!recipients.length) {
      return res.status(400).json({
        error: "No analytics report recipients configured.",
      });
    }

    run = await AnalyticsReportRun.create({
      kind: "manual",
      org_id: org._id,
      org_name: org.name || "Unknown organization",
      status: "started",
      recipients,
      range_days: 7,
      subject: `${org.name || "Organization"} Weekly Analytics Report`,
      started_at: new Date(),
    });

    const payload = await loadAnalyticsPayload(String(org._id), 7);
    const brand = safeBranding(org);
    const logoBuffer = await loadRemoteImageBuffer(brand.logoUrl);
    const pdfBuffer = await buildPdfBuffer(payload, brand, logoBuffer);

    const html = `
      <div style="font-family:Arial,sans-serif;color:#0f172a">
        <h2 style="margin-bottom:8px">${brand.orgName} Weekly Analytics Report</h2>
        <p>Your weekly branded analytics report is attached.</p>
        <p>
          Sent: <strong>${payload.summary?.sent ?? 0}</strong> ·
          Opened: <strong>${payload.summary?.opened ?? 0}</strong> ·
          Clicked: <strong>${payload.summary?.clicked ?? 0}</strong>
        </p>
      </div>
    `;

    await sendBrandedEmail({
      to: recipients,
      subject: `${brand.orgName} Weekly Analytics Report`,
      html,
      text: `${brand.orgName} Weekly Analytics Report`,
      org,
      attachments: [
        {
          filename: "weekly-analytics-report.pdf",
          content: pdfBuffer,
          contentType: "application/pdf",
        },
      ],
    });

    org.report_settings = {
      ...(org.report_settings || {}),
      last_analytics_report_sent_at: new Date(),
    };
    await org.save();

    run.status = "sent";
    run.finished_at = new Date();
    run.meta = {
      summary: payload.summary || {},
      top_documents: payload.top_documents || [],
    };
    await run.save();

    return res.json({ success: true, run_id: run._id });
  } catch (err) {
    console.error("send now analytics report error:", err);

    if (run) {
      run.status = "failed";
      run.finished_at = new Date();
      run.error_message = err?.message || "Unknown error";
      await run.save().catch(() => {});
    }

    return res.status(500).json({
      error: err?.message || "Send failed",
    });
  }
});

/* ---------------- HISTORY ---------------- */

router.get("/orgs/reports/history", requireAuth, async (req, res) => {
  try {
    const org = await getOrgForRequest(req);

    if (!org) {
      return res.status(404).json({ error: "Organization not found" });
    }

    const rows = await AnalyticsReportRun.find({
      org_id: org._id,
    })
      .sort({ started_at: -1, createdAt: -1 })
      .limit(25)
      .lean();

    return res.json({ items: rows });
  } catch (err) {
    console.error("report history load error:", err);
    return res.status(500).json({ error: "Failed to load history" });
  }
});

